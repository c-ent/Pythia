import { z } from 'zod'
import { DEFAULT_GEMINI_MODEL } from './ask/gemini.js'
import { DEFAULT_OLLAMA_CHAT_MODEL } from './ask/ollamaChat.js'
import { parseSecretsKey } from './security/secretBox.js'

// The server never listens on any other interface; outside access goes
// through Tailscale Funnel on the host. Not configurable on purpose.
export const HOST = '127.0.0.1'

// The database password is read from the same variable the Postgres container
// uses, so .env holds it once. Connection parts are separate variables rather
// than one URL so the password never sits inside a connection string.
const envSchema = z.object({
  PYTHIA_DB_HOST: z.string().min(1).default('127.0.0.1'),
  PYTHIA_DB_PORT: z.coerce.number().int().min(1).max(65_535).default(5433),
  PYTHIA_DB_USER: z.string().min(1).default('pythia'),
  PYTHIA_DB_NAME: z.string().min(1).default('pythia'),
  POSTGRES_PASSWORD: z.string().min(1, 'is required'),
  PORT: z.coerce.number().int().min(1).max(65_535).default(3000),
  OLLAMA_URL: z.url().default('http://127.0.0.1:11434'),
  // Indexing embeds (vault, repos, Keep). A 1-core host needs smaller batches
  // and a longer wait: a big note's chunks went over 120 s as one batch of 32.
  // Search keeps its own short timeout in index.ts.
  PYTHIA_EMBED_BATCH_SIZE: z.coerce.number().int().min(1).max(256).default(32),
  PYTHIA_EMBED_TIMEOUT_MS: z.coerce.number().int().min(1_000).max(3_600_000).default(120_000),
  // Unset means no vault is indexed yet; the server still starts.
  // `.env.example` ships `PYTHIA_VAULT_PATH=`, so empty counts as unset.
  PYTHIA_VAULT_PATH: z
    .string()
    .trim()
    .optional()
    .transform((value) => (value === '' ? undefined : value)),
  PYTHIA_VAULT_WATCH: z.enum(['0', '1']).default('1'),
  // Repos (T15). A JSON file listing the repos to mirror; unset turns repo
  // indexing off. Mirrors are bare clones kept under PYTHIA_REPOS_DIR.
  PYTHIA_REPOS_CONFIG: z
    .string()
    .trim()
    .optional()
    .transform((value) => (value === '' ? undefined : value)),
  PYTHIA_REPOS_DIR: z.string().trim().min(1).default('data/repos'),
  PYTHIA_REPOS_FETCH_MINUTES: z.coerce.number().int().min(5).max(1440).default(30),
  // Repo discovery (T54): lists the token owner's GitHub repos each round and
  // adds new ones. On by default whenever GITHUB_TOKEN is set; `0` turns it off.
  PYTHIA_REPOS_DISCOVER: z.enum(['0', '1']).default('1'),
  // Google Drive (R19, T61). The rclone remote for the owner's My Drive (read-only
  // scope), e.g. `gdrive:`; unset turns Drive off. The login lives in rclone.conf
  // on the host, never in .env.
  PYTHIA_DRIVE_REMOTE: z
    .string()
    .trim()
    .optional()
    .transform((value) => (value === '' ? undefined : value))
    .refine((value) => value === undefined || /^[A-Za-z0-9_][A-Za-z0-9_. -]*:\P{Cc}*$/u.test(value), 'must be an rclone remote like gdrive:'),
  PYTHIA_DRIVE_DIR: z.string().trim().min(1).default('data/gdrive'),
  // `{ "exclude": [...] }`; unset means nothing is excluded.
  PYTHIA_DRIVE_CONFIG: z
    .string()
    .trim()
    .optional()
    .transform((value) => (value === '' ? undefined : value)),
  PYTHIA_DRIVE_PULL_MINUTES: z.coerce.number().int().min(5).max(1440).default(30),
  // rclone.conf holding the Drive remote; unset means rclone's default location.
  PYTHIA_RCLONE_CONFIG: z
    .string()
    .trim()
    .optional()
    .transform((value) => (value === '' ? undefined : value)),
  // Read-only, fine-grained token for private repos on github.com. Unset
  // still works for public repos and local paths.
  GITHUB_TOKEN: optionalSecret(20),
  // Auth (T8). Generated by `pnpm --filter server auth-env`. Unset keeps
  // login and /mcp closed; it never opens them.
  PYTHIA_PASSWORD_HASH: optionalSecret(1),
  // PYTHIA_SESSION_SECRET is no longer read (T36: sessions live in the
  // database) and is ignored if an old .env still sets it.
  PYTHIA_MCP_TOKEN: optionalSecret(32),
  // Ask (T13). No key means Ask skips Gemini and uses the local model or
  // retrieval only; it never fails because the key is missing.
  GEMINI_API_KEY: optionalSecret(20),
  // Encrypts secrets saved in the database, starting with the Gemini key
  // saved in Settings (R16, T39). 32 random bytes as base64, printed by
  // `auth-env`. Unset means a key cannot be saved; a malformed value stops the
  // server rather than silently disabling saving.
  PYTHIA_SECRETS_KEY: z
    .string()
    .trim()
    .optional()
    .transform((value) => (value === '' ? undefined : value))
    .refine((value) => value === undefined || parseSecretsKey(value) !== null, 'must be 32 bytes in base64'),
  GEMINI_MODEL: z.string().trim().min(1).default(DEFAULT_GEMINI_MODEL),
  // Set but empty turns the local answer model off.
  OLLAMA_CHAT_MODEL: z.string().trim().default(DEFAULT_OLLAMA_CHAT_MODEL),
  // Built PWA (`web/dist`) to serve from the same origin as /api (T18). The
  // production image sets it; in dev Vite serves the web app, so it stays unset.
  PYTHIA_WEB_DIR: z
    .string()
    .trim()
    .optional()
    .transform((value) => (value === '' ? undefined : value)),
  // Oracle Cloud (R21, T81). All four .env values are required to turn Oracle
  // checks on; any missing value leaves Oracle `off`. Key file defaults to the
  // existing /config mount.
  PYTHIA_OCI_TENANCY: optionalOciIdentifier(10),
  PYTHIA_OCI_USER: optionalOciIdentifier(10),
  PYTHIA_OCI_FINGERPRINT: optionalOciIdentifier(10),
  PYTHIA_OCI_REGION: z
    .string()
    .trim()
    .optional()
    .transform((value) => (value === '' ? undefined : value))
    .refine((value) => value === undefined || /^[a-z]{2,6}-[a-z0-9-]+-\d+$/.test(value), 'must be an OCI region like ap-singapore-1'),
  PYTHIA_OCI_KEY_FILE: z
    .string()
    .trim()
    .optional()
    .transform((value) => (value === '' || value === undefined ? '/config/oci_api_key.pem' : value))
    .refine((value) => !/[\r\n\0]/.test(value), 'must be a valid file path'),
  // Optional read-only host root mount (e.g. /hostfs) for Settings > Server storage breakdown.
  PYTHIA_HOST_ROOT: z
    .string()
    .trim()
    .optional()
    .transform((value) => (value === '' ? undefined : value))
    .refine((value) => value === undefined || !/[\r\n\0]/.test(value), 'must be a valid directory path'),
})

/** Empty counts as unset; a set value must have at least `min` characters. */
function optionalSecret(min: number) {
  return z
    .string()
    .trim()
    .optional()
    .transform((value) => (value === '' ? undefined : value))
    .refine((value) => value === undefined || value.length >= min, `must be at least ${min} characters`)
}

/** Empty counts as unset; rejects whitespace, quotes, slashes and control characters without echoing the value. */
function optionalOciIdentifier(min: number) {
  return z
    .string()
    .trim()
    .optional()
    .transform((value) => (value === '' ? undefined : value))
    .refine(
      (value) => value === undefined || (value.length >= min && !/[\s"'\\/\0]/.test(value)),
      `must be at least ${min} safe characters`,
    )
}

export interface AuthConfig {
  passwordHash: string | null
  mcpToken: string | null
}

export interface VaultConfig {
  root: string
  watch: boolean
}

export interface ReposConfig {
  /** Path of the JSON repo list (see `ingest/repoConfig.ts`). */
  configFile: string
  mirrorsDir: string
  fetchIntervalMs: number
  githubToken: string | null
  /** Add the token owner's new GitHub repos each round (T54); on unless `PYTHIA_REPOS_DISCOVER=0`. */
  discover: boolean
}

export interface DriveConfig {
  /** rclone remote for My Drive, e.g. `gdrive:`. */
  remote: string
  /** The mirror rclone writes and the indexer reads. */
  mirrorDir: string
  /** `/config/gdrive.json` with the exclude list, or null for none. */
  configFile: string | null
  pullIntervalMs: number
  /** rclone.conf path, or null for rclone's default. */
  rcloneConfig: string | null
}

export interface DbConfig {
  host: string
  port: number
  user: string
  database: string
  password: string
}

export interface AskConfig {
  geminiApiKey: string | null
  geminiModel: string
  /** Null turns the local answer model off. */
  ollamaChatModel: string | null
}

export interface EmbedConfig {
  /** Chunks per `/api/embed` request when indexing. */
  batchSize: number
  /** Per indexing request; search uses its own short timeout. */
  timeoutMs: number
}

export interface OciConfig {
  tenancyId: string
  userId: string
  fingerprint: string
  region: string
  keyFile: string
}

export interface Config {
  host: typeof HOST
  port: number
  db: DbConfig
  ollamaUrl: string
  embed: EmbedConfig
  vault: VaultConfig | null
  repos: ReposConfig | null
  /** Null when `PYTHIA_VAULT_PATH` is unset. */
  vaultPath: string | null
  /** Read-only GitHub API token for connection health checks. */
  githubToken: string | null
  /** Null when PYTHIA_DRIVE_REMOTE is unset. */
  drive: DriveConfig | null
  /** Null when any required `PYTHIA_OCI_*` variable is unset. */
  oci: OciConfig | null
  /** Read-only host root mount path for storage breakdown, or null when unset. */
  hostRoot: string | null
  auth: AuthConfig
  ask: AskConfig
  /** `PYTHIA_SECRETS_KEY` as 32 bytes, or null when unset. */
  secretsKey: Buffer | null
  /** Directory of the built web app, or null when something else serves it. */
  webDir: string | null
}

export class ConfigError extends Error {
  override name = 'ConfigError'
}

/**
 * Parses and validates the environment once at startup. Error messages name
 * the invalid variables but never echo their values, which may be secrets.
 */
export function loadConfig(env: Record<string, string | undefined>): Config {
  const result = envSchema.safeParse(env)
  if (!result.success) {
    const problems = result.error.issues.map((issue) => `${issue.path.join('.')} ${issue.message}`)
    throw new ConfigError(`Invalid environment: ${problems.join('; ')}`)
  }
  const data = result.data
  return {
    host: HOST,
    port: data.PORT,
    db: {
      host: data.PYTHIA_DB_HOST,
      port: data.PYTHIA_DB_PORT,
      user: data.PYTHIA_DB_USER,
      database: data.PYTHIA_DB_NAME,
      password: data.POSTGRES_PASSWORD,
    },
    ollamaUrl: data.OLLAMA_URL,
    vaultPath: data.PYTHIA_VAULT_PATH ?? null,
    githubToken: data.GITHUB_TOKEN ?? null,
    embed: {
      batchSize: data.PYTHIA_EMBED_BATCH_SIZE,
      timeoutMs: data.PYTHIA_EMBED_TIMEOUT_MS,
    },
    vault:
      data.PYTHIA_VAULT_PATH === undefined
        ? null
        : {
            root: data.PYTHIA_VAULT_PATH,
            watch: data.PYTHIA_VAULT_WATCH === '1',
          },
    repos:
      data.PYTHIA_REPOS_CONFIG === undefined
        ? null
        : {
            configFile: data.PYTHIA_REPOS_CONFIG,
            mirrorsDir: data.PYTHIA_REPOS_DIR,
            fetchIntervalMs: data.PYTHIA_REPOS_FETCH_MINUTES * 60_000,
            githubToken: data.GITHUB_TOKEN ?? null,
            discover: data.PYTHIA_REPOS_DISCOVER === '1',
          },
    drive:
      data.PYTHIA_DRIVE_REMOTE === undefined
        ? null
        : {
            remote: data.PYTHIA_DRIVE_REMOTE,
            mirrorDir: data.PYTHIA_DRIVE_DIR,
            configFile: data.PYTHIA_DRIVE_CONFIG ?? null,
            pullIntervalMs: data.PYTHIA_DRIVE_PULL_MINUTES * 60_000,
            rcloneConfig: data.PYTHIA_RCLONE_CONFIG ?? null,
          },
    oci:
      data.PYTHIA_OCI_TENANCY === undefined ||
      data.PYTHIA_OCI_USER === undefined ||
      data.PYTHIA_OCI_FINGERPRINT === undefined ||
      data.PYTHIA_OCI_REGION === undefined
        ? null
        : {
            tenancyId: data.PYTHIA_OCI_TENANCY,
            userId: data.PYTHIA_OCI_USER,
            fingerprint: data.PYTHIA_OCI_FINGERPRINT,
            region: data.PYTHIA_OCI_REGION,
            keyFile: data.PYTHIA_OCI_KEY_FILE,
          },
    hostRoot: data.PYTHIA_HOST_ROOT ?? null,
    auth: {
      passwordHash: data.PYTHIA_PASSWORD_HASH ?? null,
      mcpToken: data.PYTHIA_MCP_TOKEN ?? null,
    },
    ask: {
      geminiApiKey: data.GEMINI_API_KEY ?? null,
      geminiModel: data.GEMINI_MODEL,
      ollamaChatModel: data.OLLAMA_CHAT_MODEL === '' ? null : data.OLLAMA_CHAT_MODEL,
    },
    secretsKey: data.PYTHIA_SECRETS_KEY === undefined ? null : parseSecretsKey(data.PYTHIA_SECRETS_KEY),
    webDir: data.PYTHIA_WEB_DIR ?? null,
  }
}
