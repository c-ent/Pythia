import type pg from 'pg'

// Test-only helper for the opt-in Postgres suites (PYTHIA_DB_TESTS=1).
//
// pool.end() resolves before the server has finished closing each backend.
// Dropping the database WITH (FORCE) at that moment makes Postgres send
// 57P01 ("terminating connection due to administrator command") to a pg
// client that is already ending, and that surfaces in vitest as an unhandled
// error. Waiting until the database has no backends left avoids the race;
// FORCE stays as a last resort if one never goes away.
export async function dropTestDatabase(admin: pg.Client, dbName: string, timeoutMs = 5000): Promise<void> {
  const deadline = Date.now() + timeoutMs
  for (;;) {
    const { rows } = await admin.query<{ n: string }>('SELECT count(*) AS n FROM pg_stat_activity WHERE datname = $1', [
      dbName,
    ])
    if (Number(rows[0]?.n ?? 0) === 0 || Date.now() >= deadline) break
    await new Promise((resolve) => setTimeout(resolve, 50))
  }
  // dbName is generated by the test, never user input, so quoting it is safe.
  await admin.query(`DROP DATABASE IF EXISTS "${dbName}" WITH (FORCE)`)
}
